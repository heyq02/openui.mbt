import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const wasmPath = resolve(here, '../_build/wasm-gc/release/build/wasm/wasm.wasm');
const bytes = readFileSync(wasmPath);
const wasmBase64 = bytes.toString('base64');

writeFileSync(
  resolve(here, 'parser.wasm.js'),
  `// Generated by build.mjs from the Wasm-GC release build.\nexport const wasmBase64 = ${JSON.stringify(wasmBase64)};\n`,
);
